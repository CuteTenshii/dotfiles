-- See https://wiki.hypr.land/Configuring/Basics/Window-Rules/
-- and https://wiki.hypr.land/Configuring/Basics/Workspace-Rules/

hl.window_rule({
    -- Ignore maximize requests from all apps. You'll probably like this.
    name  = "suppress-maximize-events",
    match = { class = ".*" },

    suppress_event = "maximize",
})

hl.window_rule({
    -- Fix some dragging issues with XWayland
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },

    no_focus = true,
})

hl.window_rule({
    -- Chromium/Electron menus have an empty class and title and render wrong with blur
    name  = "no-blur-chromium-menus",
    match = { class = "^()$", title = "^()$" },

    no_blur = true,
})

hl.window_rule({
    -- Steam's main window opens floating by default
    name  = "tile-steam",
    match = { class = "steam", title = "Steam" },

    float = false,
})

hl.layer_rule({
    name  = "blur-waybar",
    match = { namespace = "waybar" },

    blur = true,
    -- Don't blur behind fully transparent pixels, so the bar's gaps stay clear
    ignore_alpha = 0,
})
